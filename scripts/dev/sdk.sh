#!/usr/bin/env bash
# 由契约生成前端 TS 类型 + 类型安全客户端入口（web-sdk/src/gen/，禁止手改）。
set -euo pipefail
cd "$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
OUT=web-sdk/src/gen; rm -rf "$OUT"; mkdir -p "$OUT"
{
  echo "// Code generated by scripts/dev/sdk.sh. DO NOT EDIT."
  echo 'import createClient, { type ClientOptions } from "openapi-fetch";'
} > "$OUT/index.ts"
body=""
while read -r name _; do
  npx -y openapi-typescript@7 "services/$name/src/main/resources/openapi.yaml" -o "$OUT/$name.ts" >/dev/null
  type="$(echo "${name:0:1}" | tr a-z A-Z)${name:1}Paths"
  echo "import type { paths as $type, components as ${type%Paths}Components } from \"./$name\";" >> "$OUT/index.ts"
  echo "export type ${type%Paths}Schemas = ${type%Paths}Components[\"schemas\"];" >> "$OUT/index.ts"
  body+="    $name: createClient<$type>({ ...opts, baseUrl: \`\${gateway}/api/$name\` }),\n"
done < <(scripts/dev/services.sh)
{
  echo ""
  echo "/** 所有请求经 gateway；切换真实后端 / mock 只需改 gateway 上游，前端零改动。 */"
  echo 'export function createApi(gateway = "http://localhost:8080", opts: ClientOptions = {}) {'
  echo "  return {"
  printf "%b" "$body"
  echo "  };"
  echo "}"
} >> "$OUT/index.ts"
echo "sdk: generated $(ls "$OUT" | wc -l) files in $OUT"
